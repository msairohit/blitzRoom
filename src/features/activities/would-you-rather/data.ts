/**
 * Returns a randomized pool of dilemmas based on category, count, and optional custom dilemmas.
 */
export function getDilemmaPool(
  category: WouldYouRatherCategory | 'all',
  count: number,
  customDilemmas?: Dilemma[]
): Dilemma[] {
  let pool = [...DILEMMA_BANK];

  if (category !== 'all') {
    pool = pool.filter((d) => d.category === category);
  }

  // Prepend custom dilemmas if any
  if (customDilemmas && customDilemmas.length > 0) {
    pool = [...customDilemmas, ...pool];
  }

  // Fisher-Yates shuffle
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }

  return pool.slice(0, Math.min(count, pool.length));
}
